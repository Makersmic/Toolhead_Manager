"""Maintenance tasks: the API the portal, the console (PM_STATUS) and the boot reminder use.

    myrhino/maintenance/tasks.json     areas, lists, status codes, the Task Library and Task Books,
                                       the tasks themselves, settings
    myrhino/maintenance/history.json   every completion / skip / status change / meter adjustment
    myrhino/maintenance/meters.json    usage meters (meters.py)
    myrhino/maintenance_status.cfg     generated: what is due, for the Mainsail prompt after a restart

All three JSON files live in the config folder, so klipper-backup keeps them. Maintenance NEVER
blocks a job: it reminds, it does not lock anything.

Words used here
    asset     what a task is for: "machine:<area>", "tool:<name>" or "hw:<system hardware name>"
    template  a task in the Task Library (no asset, no schedule state)
    book      a Task Book: a named group of templates. Assigning it to an asset adds one task per
              template there. Those tasks are LINKED: editing the template updates every one of them.
    status    the built-in states the schedule works out (overdue, due soon...) plus custom status
              codes a person sets by hand ("Pending - Waiting on parts"), each with rules.
"""
