def _flag(v):
    return v in (True, 1, "1", "true", "True", "on", "yes")


def _text(v, label, maxlen, safe=True):
    s = " ".join(str(v or "").split()) if safe else str(v or "").strip()
    if len(s) > maxlen:
        raise Fail(f"{label} is too long (max {maxlen} characters)")
    if safe and not SAFE_TEXT.match(s):
        raise Fail(f"{label} may only contain {SAFE_TEXT_HELP}")
    return s


def _lines(v, label, maxlen, maxn=MAX_LIST):
    items = v.splitlines() if isinstance(v, str) else list(v or [])
    items = [str(i).strip() for i in items if str(i).strip()]
    if len(items) > maxn:
        raise Fail(f"{label}: at most {maxn} lines")
    for i in items:
        if len(i) > maxlen:
            raise Fail(f"{label}: each line at most {maxlen} characters")
    return items


def _num(v, label, lo, hi, integer=False):
    try:
        x = float(v)
    except (TypeError, ValueError):
        raise Fail(f"{label} must be a number")
    if not (lo <= x <= hi):
        raise Fail(f"{label} must be between {lo:g} and {hi:g}")
    return int(round(x)) if integer else x


def _new_id(prefix, taken):
    while True:
        i = prefix + secrets.token_hex(4)
        if i not in taken:
            return i


class MaintService:
    def __init__(self, paths, tool_service, now=time.time):
        self.paths, self.tools_svc, self.now = paths, tool_service, now
        d = os.path.join(paths.cfg, "myrhino", "maintenance")
        self.tasks_path, self.history_path = os.path.join(d, "tasks.json"), os.path.join(d, "history.json")
        self.status_cfg = os.path.join(paths.cfg, "myrhino", "maintenance_status.cfg")
        self.meters = meters.MeterStore(os.path.join(d, "meters.json"))
        self.lock = threading.RLock()
        self._tools_cache, self._tools_key = None, None
        self._boot_sig = None

    # ------------------------------------------------------------------ files
    def _fresh(self):
        return {"version": 2, "areas": copy.deepcopy(library.DEFAULT_AREAS), "tasks": {}, "settings": {"boot_reminder": True}}

    def _load_tasks(self):
        if not os.path.exists(self.tasks_path):
            d = self._fresh()
        else:
            try:
                with open(self.tasks_path, encoding="utf-8") as f:
                    d = json.load(f)
                if not isinstance(d.get("tasks"), dict):
                    raise ValueError("no tasks object")
            except (OSError, ValueError) as e:
                raise Fail(f"{self.tasks_path} is unreadable: {e}")
        d.setdefault("areas", copy.deepcopy(library.DEFAULT_AREAS))
        d.setdefault("settings", {}).setdefault("boot_reminder", True)
        d.setdefault("types", dict(DEFAULT_TYPES))
        pr = d.setdefault("priorities", dict(DEFAULT_PRIORITIES))
        for p in PRIORITY_IDS:
            pr.setdefault(p, DEFAULT_PRIORITIES[p])
        st = d.setdefault("statuses", {})
        b = st.setdefault("builtin", {})
        for k, v in BUILTIN_STATUSES.items():
            b.setdefault(k, {"label": v["label"], "color": v["color"]})
        st.setdefault("custom", copy.deepcopy(DEFAULT_CUSTOM_STATUSES))
        if "templates" not in d:                    # first run of the Task Library: seed the starter tasks
            d["templates"] = library.starter_templates()
            d["books"] = {b["id"]: {"name": b["name"], "description": b["description"], "templates": list(b["templates"]),
                                    "assigned": [], "origin": "starter", "for": b.get("for", "tool")} for b in library.STARTER_BOOKS}
        d.setdefault("books", {})
        return d

    def _load_history(self):
        if not os.path.exists(self.history_path):
            return []
        try:
            with open(self.history_path, encoding="utf-8") as f:
                return list(json.load(f).get("records", []))
        except (OSError, ValueError, AttributeError) as e:
            raise Fail(f"{self.history_path} is unreadable: {e}")

    @staticmethod
    def _atomic(path, obj):
        os.makedirs(os.path.dirname(path), exist_ok=True)
        tmp = path + ".tmp"
        with open(tmp, "w", encoding="utf-8") as f:
            json.dump(obj, f, indent=1, sort_keys=True)
        os.replace(tmp, path)

    def _save_tasks(self, d):
        self._atomic(self.tasks_path, d)
        self.write_boot_cfg(force=True)

    def _append_history(self, rec):
        h = self._load_history()
        h.append(rec)
        self._atomic(self.history_path, {"version": 1, "records": h[-MAX_HISTORY:]})

    def _log(self, d, t, tid, action, notes="", **extra):
        self._append_history({"id": "h" + secrets.token_hex(4), "task": tid, "title": t["title"], "asset": t["asset"],
                              "asset_label": self.asset_label(t["asset"], d["areas"]), "action": action, "at": extra.pop("at", self.now()),
                              "logged": self.now(), "notes": notes, **extra})

    # ------------------------------------------------------------------ tools + hardware
    def tools(self):
        """{slot: {"name", "type", "kind_code", "builtin"}} - cached until the registry or variables change."""
        key = tuple(os.path.getmtime(p) if os.path.exists(p) else 0
                    for p in (self.paths.registry_json, self.paths.variables_cfg))
        if self._tools_cache is None or key != self._tools_key:
            reg = registry.load(self.paths)
            out = {}
            try:
                for t in self.tools_svc.list_tools():
                    out[t["slot"]] = {"name": t["name"], "type": t["type"], "builtin": t["builtin"],
                                      "kind_code": reg["tools"].get(t["name"], {}).get("kind", "")}
            except Fail:
                out = self._tools_cache or {}
            self._tools_cache, self._tools_key = out, key
        return self._tools_cache

    def tool_names(self):
        return {t["name"]: t for t in self.tools().values()}

    def hardware_names(self):
        try:
            return {n: hw for n, hw in registry.load(self.paths).get("hardware", {}).items()}
        except Fail:
            return {}

    def collector(self, moonraker):
        return meters.Collector(self.meters, moonraker, self.tools, on_change=lambda: self.write_boot_cfg())

    # ------------------------------------------------------------------ assets
    def asset_label(self, asset, areas):
        kind, _, ref = asset.partition(":")
        if kind == "tool":
            return ref
        if kind == "hw":
            return ref.replace("_", " ")
        if asset == "machine":
            return "Whole machine"
        return next((a["label"] for a in areas if a["id"] == ref), ref)

    def _check_asset(self, asset, d, allow_machine=False):
        kind, _, ref = (asset or "").partition(":")
        if allow_machine and asset == "machine":
            return asset
        if kind == "machine" and any(a["id"] == ref for a in d["areas"]):
            return asset
        if kind == "tool" and ref in self.tool_names():
            return asset
        if kind == "hw" and ref in self.hardware_names():
            return asset
        raise Fail("Choose what the task is for: a part of the machine, a tool or system hardware")

    @staticmethod
    def _tool_of(asset):
        return asset.partition(":")[2] if asset.startswith("tool:") else None

    # ------------------------------------------------------------------ status
    def _readers(self, task, frozen=None):
        tool = self._tool_of(task["asset"])

        def value(rule):
            if frozen is not None:
                k = schedule.meter_key(rule)
                if k in frozen:
                    return frozen[k]
            return self.meters.value(rule.get("scope", "machine"), rule["meter"], tool)

        def rate(rule):
            if frozen is not None:
                return None
            return self.meters.rate(rule.get("scope", "machine"), rule["meter"], tool, now=self.now())
        return value, rate

    def status_defs(self, d):
        """{id: {label, color, hex, builtin, ...rules}} for every status, built-in and custom."""
        out = {}
        for k, v in BUILTIN_STATUSES.items():
            b = d["statuses"]["builtin"].get(k, {})
            col = b.get("color", v["color"])
            out[k] = {"id": k, "label": b.get("label", v["label"]), "color": col, "hex": COLORS.get(col, COLORS["grey"]),
                      "builtin": True, "help": v["help"]}
        for c in d["statuses"]["custom"]:
            out[c["id"]] = {**c, "hex": COLORS.get(c["color"], COLORS["grey"]), "builtin": False}
        return out

    def status_of(self, task, now=None, defs=None):
        now = now or self.now()
        hold = task.get("hold")
        sdef = (defs or {}).get(hold["status"]) if hold else None
        if hold and sdef and sdef.get("clock") == "pause":         # frozen where it was when the status was set
            value, rate = self._readers(task, frozen=hold.get("meters") or {})
            st = schedule.task_status(task, hold["since"], value, rate, meters.meter_defs())
        else:
            value, rate = self._readers(task)
            st = schedule.task_status(task, now, value, rate, meters.meter_defs())
        if hold and sdef:
            st["hold"] = {"id": hold["status"], "label": sdef["label"], "hex": sdef["hex"], "list": sdef.get("list", "own"),
                          "since": hold["since"], "note": hold.get("note", ""), "clock": sdef.get("clock", "none"),
                          "boot_prompt": bool(sdef.get("boot_prompt")),
                          "until": hold["since"] + sdef.get("expiry_days", 0) * 86400 if sdef.get("expiry") == "days" else None,
                          "expiry": sdef.get("expiry", "never")}
        return st

    def _expired(self, task, sdef, now):
        hold = task["hold"]
        if sdef.get("expiry") == "days":
            return now >= hold["since"] + float(sdef.get("expiry_days") or 0) * 86400
        if sdef.get("expiry") == "meter":
            snap = self.meters.snapshot(self._tool_of(task["asset"]))
            keys = {schedule.meter_key(r) for r in task.get("rules", []) if r["kind"] == "meter"} or {"machine.prod_h"}
            return any(snap.get(k, 0) > (hold.get("meters") or {}).get(k, snap.get(k, 0)) + 0.01 for k in keys)
        return False

    def _release(self, task, sdef, now):
        """Take a custom status off a task, crediting the paused time and use if its clock was paused."""
        hold = task.pop("hold", None)
        if not hold or not sdef or sdef.get("clock") != "pause":
            return
        p = task.setdefault("paused", {"s": 0.0, "meters": {}})
        p["s"] = float(p.get("s") or 0) + max(0.0, now - hold["since"])
        snap = self.meters.snapshot(self._tool_of(task["asset"]))
        for k, v in (hold.get("meters") or {}).items():
            if k in snap:
                p["meters"][k] = float(p["meters"].get(k) or 0) + max(0.0, snap[k] - v)

    def _sweep(self, d):
        """Release custom statuses whose expiry rule has fired. Returns True if anything changed."""
        now, defs, changed = self.now(), self.status_defs(d), False
        for tid, t in d["tasks"].items():
            hold = t.get("hold")
            if not hold:
                continue
            sdef = defs.get(hold["status"])
            if sdef is None or self._expired(t, sdef, now):
                label = sdef["label"] if sdef else hold["status"]
                self._release(t, sdef, now)
                self._log(d, t, tid, "status_cleared", f"{label} ended by itself", status=label)
                changed = True
        return changed

    def overview(self):
        """Everything the maintenance screens need, in one call."""
        with self.lock:
            d = self._load_tasks()
            if self._sweep(d):
                self._atomic(self.tasks_path, d)
            now, defs = self.now(), self.status_defs(d)
            tasks = []
            for tid, t in d["tasks"].items():
                st = self.status_of(t, now, defs) if t.get("enabled", True) and not t.get("archived") else None
                tasks.append({**t, "id": tid, "asset_label": self.asset_label(t["asset"], d["areas"]), "status": st,
                              "link_info": self._link_info(d, t)})
            counts = {"overdue": 0, "due_soon": 0, "snoozed": 0, "held": 0}
            for t in tasks:
                st = t["status"]
                if not st:
                    continue
                if st.get("hold"):
                    counts["held"] += 1
                    if st["hold"]["list"] != "due":
                        continue
                if st["state"] in ("overdue", "due_soon"):
                    counts["snoozed" if st["snoozed"] else st["state"]] += 1
            return {"ok": True, "areas": d["areas"], "settings": d["settings"], "tasks": tasks, "counts": counts,
                    "meters": self.meter_report(), "types": d["types"], "priorities": {p: d["priorities"][p] for p in PRIORITY_IDS},
                    "statuses": list(defs.values()), "colors": COLORS,
                    "tools": [{"name": t["name"], "type": t["type"], "builtin": t["builtin"], "kind_code": t["kind_code"]}
                              for _, t in sorted(self.tools().items())],
                    "hardware": [{"name": n, "label": n.replace("_", " "), "category": hw.get("category", "")}
                                 for n, hw in sorted(self.hardware_names().items())],
                    "now": now}

    def _link_info(self, d, t):
        link = t.get("link")
        if not link:
            return None
        tpl = d["templates"].get(link.get("template"))
        book = d["books"].get(link.get("book") or "")
        users = sum(1 for x in d["tasks"].values() if (x.get("link") or {}).get("template") == link.get("template") and not x.get("archived"))
        return {"template": link.get("template"), "template_title": tpl["title"] if tpl else "", "book": link.get("book") or "",
                "book_name": book["name"] if book else "", "uses": users}

    def meter_report(self):
        md, now = self.meters.data, self.now()
        def rows(scope, defs, tool=None):
            return [{"meter": k, "label": v["label"], "unit": v["unit"], "help": v["help"], "event": v.get("event", ""),
                     "noun": v["noun"], "value": self.meters.value(scope, k, tool),
                     "per_day": self.meters.rate(scope, k, tool, now=now)} for k, v in defs.items()]
        names = self.tool_names()
        return {"tracking_since": md.get("tracking_since"), "imported_jobs": md.get("imported_jobs", 0),
                "machine": rows("machine", meters.MACHINE_METERS),
                "tools": {n: rows("tool", meters.TOOL_METERS, n) for n in names},
                "archived_tools": sorted(n for n in md.get("tools", {}) if n not in names),
                "adjustments": md.get("adjustments", [])[-20:]}

    # ------------------------------------------------------------------ validation
    def _clean_rule(self, r, asset):
        """asset None = a library template (a tool meter then makes it a tool-only template)."""
        kind = r.get("kind")
        if kind == "time":
            out = {"kind": "time", "every": _num(r.get("every"), "Interval", 1, 3650, integer=True),
                   "unit": r.get("unit") if r.get("unit") in UNITS else "days"}
            if r.get("lead") not in (None, ""):
                out["lead"] = _num(r["lead"], "Early alarm", 0, 3650)
                out["lead_unit"] = r.get("lead_unit") if r.get("lead_unit") in UNITS else "days"
            return out
        if kind == "date":
            try:
                schedule.day_start(str(r.get("on")))
            except (ValueError, TypeError):
                raise Fail("Choose the date for a one-off task")
            return {"kind": "date", "on": str(r["on"]), "lead": _num(r.get("lead", 7) or 0, "Early alarm", 0, 365)}
        if kind == "meter":
            scope = "tool" if r.get("scope") == "tool" else "machine"
            defs = meters.TOOL_METERS if scope == "tool" else meters.MACHINE_METERS
            if r.get("meter") not in defs:
                raise Fail("Choose what the task counts")
            if scope == "tool" and asset is not None and not asset.startswith("tool:"):
                raise Fail("A tool meter needs the task to belong to a tool")
            if _flag(r.get("event")):
                if not defs[r["meter"]].get("event"):
                    raise Fail("That meter is not an event")
                return {"kind": "meter", "meter": r["meter"], "scope": scope, "every": 1, "lead": 0, "event": True}
            out = {"kind": "meter", "meter": r["meter"], "scope": scope,
                   "every": _num(r.get("every"), "Interval", 0.1, 1e6)}
            if r.get("lead") not in (None, ""):
                out["lead"] = _num(r["lead"], "Early alarm", 0, out["every"])
            return out
        raise Fail("Each schedule rule needs a kind: time, usage, event or date")

    def _clean_def(self, f, d, asset, old=None):
        """The definition part of a task or template (everything except what it is for and its state)."""
        t = dict(old or {})
        t["title"] = _text(f.get("title"), "Title", 80)
        if not t["title"]:
            raise Fail("Give the task a title")
        t["type"] = f.get("type") if f.get("type") in d["types"] else ("inspect" if "inspect" in d["types"] else next(iter(d["types"])))
        t["priority"] = f.get("priority") if f.get("priority") in PRIORITY_IDS else "normal"
        rules = list(f.get("rules") or [])
        if not rules:
            raise Fail("Add at least one schedule rule")
        if len(rules) > MAX_RULES:
            raise Fail(f"At most {MAX_RULES} rules per task")
        t["rules"] = [self._clean_rule(r, asset) for r in rules]
        t["anchor"] = "calendar" if f.get("anchor") == "calendar" else "completion"
        if t["anchor"] == "calendar":
            try:
                schedule.day_start(str(f.get("first_due")))
            except (TypeError, ValueError):
                raise Fail("Choose the first due date for a fixed-calendar schedule")
            t["first_due"] = str(f["first_due"])
        else:
            t.pop("first_due", None)
        t["steps"] = _lines(f.get("steps"), "Steps", 200)
        t["parts"] = _lines(f.get("parts"), "Parts", 120)
        t["tools_needed"] = _text(f.get("tools_needed"), "Tools needed", 200, safe=False)
        t["minutes"] = _num(f.get("minutes") or 0, "Time needed", 0, 1440, integer=True)
        t["safety"] = _text(f.get("safety"), "Safety notes", 500, safe=False)
        t["notes"] = _text(f.get("notes"), "Notes", 1000, safe=False)
        links = _lines(f.get("links"), "Links", 300, 5)
        for u in links:
            if urlparse(u).scheme not in ("http", "https"):
                raise Fail("Links must start with http:// or https://")
        t["links"] = links
        t["remind_boot"] = _flag(f.get("remind_boot", True))
        return t

    def _clean_task(self, f, d, old=None):
        asset = self._check_asset(f.get("asset"), d)
        t = self._clean_def(f, d, asset, old)
        t["asset"] = asset
        t["enabled"] = _flag(f.get("enabled", True))
        return t

    def _baseline(self, f, task):
        """Where counting starts for a new task: now, or 'last done on <date> at these readings'."""
        now = self.now()
        snap = self.meters.snapshot(self._tool_of(task["asset"]))
        start = {"at": now, "meters": snap}
        lb = f.get("last_done") or {}
        if lb.get("when") == "date":
            try:
                at = schedule.day_start(str(lb.get("date")))
            except (TypeError, ValueError):
                raise Fail("Choose the date it was last done")
            if at > now:
                raise Fail("The last-done date cannot be in the future")
            start["at"] = at
            for k, v in (lb.get("readings") or {}).items():
                if k in snap and v not in (None, ""):
                    start["meters"][k] = _num(v, "Reading", 0, 1e7)
        return start

    # ------------------------------------------------------------------ tasks
    def create(self, f, template=None):
        with self.lock:
            d = self._load_tasks()
            if len(d["tasks"]) >= MAX_TASKS:
                raise Fail(f"At most {MAX_TASKS} tasks")
            t = self._clean_task(f, d)
            t["created"] = self.now()
            t["start"] = self._baseline(f, t)
            t["last"] = None
            if template:
                t["template"] = template
            tid = _new_id("t", d["tasks"])
            d["tasks"][tid] = t
            self._save_tasks(d)
            return {"ok": True, "id": tid}

    def update(self, tid, f):
        """Edit a task. A task linked to the Task Library only takes its own settings here (paused or
        not); its definition is the template's - edit that, or detach the task first."""
        with self.lock:
            d = self._load_tasks()
            old = d["tasks"].get(tid)
            if old is None:
                raise Fail("No such task")
            if _flag(f.get("detach")) and old.get("link"):
                old.pop("link")
                self._save_tasks(d)
                return {"ok": True, "id": tid, "detached": True}
            if old.get("link"):
                old["enabled"] = _flag(f.get("enabled", old.get("enabled", True)))
                self._save_tasks(d)
                return {"ok": True, "id": tid, "linked": True}
            t = self._clean_task(f, d, old)
            if t["asset"] != old["asset"]:      # readings belong to the old asset; restart counting
                t["start"], t["last"] = self._baseline({}, t), None
                t.pop("paused", None)
            d["tasks"][tid] = t
            self._save_tasks(d)
            return {"ok": True, "id": tid}

    def delete(self, tid):
        with self.lock:
            d = self._load_tasks()
            if d["tasks"].pop(tid, None) is None:
                raise Fail("No such task")
            self._save_tasks(d)
            return {"ok": True}

    def _log_options(self, d):
        defs = self.status_defs(d)
        return {"done": "Done", "skipped": "Skipped - not needed this time",
                **{c["id"]: c["label"] for c in d["statuses"]["custom"] if c.get("log_option")}}, defs

    def complete(self, tid, f):
        """Log work on a task: done, skipped, or one of the custom statuses offered in the Log work list."""
        with self.lock:
            d = self._load_tasks()
            t = d["tasks"].get(tid)
            if t is None:
                raise Fail("No such task")
            options, defs = self._log_options(d)
            action = f.get("action") or "done"
            if action not in options:
                raise Fail("Choose what happened")
            if action not in ("done", "skipped"):
                return self._set_status(d, tid, t, action, f.get("notes"), via_log=True)
            now = self.now()
            at = now
            if f.get("date"):
                try:
                    at = schedule.day_start(str(f["date"]))
                    if str(f["date"]) == time.strftime("%Y-%m-%d", time.localtime(now)):
                        at = now
                except (TypeError, ValueError):
                    raise Fail("Bad date")
                if at > now + 60:
                    raise Fail("The date cannot be in the future")
            snap = self.meters.snapshot(self._tool_of(t["asset"]))
            status = self.status_of(t, now, defs)
            if t.get("hold"):
                self._release(t, defs.get(t["hold"]["status"]), now)
            t["last"] = {"at": at, "meters": snap, "action": action}
            t.pop("snooze_until", None)
            t.pop("paused", None)
            self._save_tasks(d)
            self._log(d, t, tid, action, _text(f.get("notes"), "Notes", 1000, safe=False), at=at,
                      was=status["state"], readings=snap, status=(status.get("hold") or {}).get("label", ""))
            return {"ok": True}

    def set_status(self, tid, f):
        """Set (or clear, with status "") a custom status by hand."""
        with self.lock:
            d = self._load_tasks()
            t = d["tasks"].get(tid)
            if t is None:
                raise Fail("No such task")
            return self._set_status(d, tid, t, f.get("status") or "", f.get("note"))

    def _set_status(self, d, tid, t, sid, note, via_log=False):
        defs, now = self.status_defs(d), self.now()
        note = _text(note, "Note", 300, safe=False)
        if not sid:
            if not t.get("hold"):
                return {"ok": True}
            label = defs.get(t["hold"]["status"], {}).get("label", t["hold"]["status"])
            self._release(t, defs.get(t["hold"]["status"]), now)
            self._save_tasks(d)
            self._log(d, t, tid, "status_cleared", note, status=label)
            return {"ok": True}
        sdef = defs.get(sid)
        if sdef is None or sdef["builtin"]:
            raise Fail("Choose one of your status codes")
        if sdef.get("note_required") and not note:
            raise Fail(f"'{sdef['label']}' needs a note - say why (which parts, who, when)")
        before = self.status_of(t, now, defs)
        if t.get("hold"):
            self._release(t, defs.get(t["hold"]["status"]), now)
        snap = self.meters.snapshot(self._tool_of(t["asset"]))
        if sdef.get("clock") == "done":                     # counts as done: the interval starts again
            t["last"] = {"at": now, "meters": snap, "action": sid}
            t.pop("paused", None)
        t.pop("snooze_until", None)
        t["hold"] = {"status": sid, "since": now, "note": note, "meters": snap}
        self._save_tasks(d)
        self._log(d, t, tid, "status", note, status=sdef["label"], was=before["state"], readings=snap)
        return {"ok": True}

    def snooze(self, tid, days):
        with self.lock:
            d = self._load_tasks()
            t = d["tasks"].get(tid)
            if t is None:
                raise Fail("No such task")
            days = _num(days, "Snooze", 0, 90)
            if days:
                t["snooze_until"] = self.now() + days * 86400
            else:
                t.pop("snooze_until", None)
            self._save_tasks(d)
            return {"ok": True}

    # ------------------------------------------------------------------ admin lists
    def save_areas(self, areas):
        with self.lock:
            d = self._load_tasks()
            clean, seen = [], set()
            for a in areas or []:
                label = _text(a.get("label"), "Area name", 40)
                aid = (a.get("id") or re.sub(r"[^a-z0-9_]+", "_", label.lower()).strip("_")[:32] or "area")
                if not AREA_ID.match(aid) or aid in seen:
                    aid = f"area_{secrets.token_hex(3)}"
                if label:
                    clean.append({"id": aid, "label": label})
                    seen.add(aid)
            used = {t["asset"].partition(":")[2] for t in d["tasks"].values() if t["asset"].startswith("machine:") and not t.get("archived")}
            missing = used - seen
            if missing:
                raise Fail("These areas still have tasks: " + ", ".join(sorted(missing)) + ". Move or delete the tasks first.")
            if not clean:
                raise Fail("Keep at least one area")
            d["areas"] = clean
            self._save_tasks(d)
            return {"ok": True, "areas": clean}

    def save_lists(self, f):
        """Kinds of work (add / rename / remove unused) and priority names (rename only)."""
        with self.lock:
            d = self._load_tasks()
            if "types" in f:
                types, seen = {}, set()
                for raw in f["types"] or []:
                    label = _text(raw.get("label"), "Kind of work", 30)
                    if not label:
                        continue
                    tid = raw.get("id") or re.sub(r"[^a-z0-9_]+", "_", label.lower()).strip("_")[:24] or "work"
                    if not AREA_ID.match(tid) or tid in seen:
                        tid = f"work_{secrets.token_hex(2)}"
                    seen.add(tid)
                    types[tid] = label
                if not types:
                    raise Fail("Keep at least one kind of work")
                if len(types) > MAX_TYPES:
                    raise Fail(f"At most {MAX_TYPES} kinds of work")
                used = {t.get("type") for t in list(d["tasks"].values()) + list(d["templates"].values())}
                gone = [d["types"][k] for k in d["types"] if k not in types and k in used]
                if gone:
                    raise Fail(f"Tasks still use {', '.join(gone)} - change them first, or rename it instead")
                d["types"] = types
            if "priorities" in f:
                for p in PRIORITY_IDS:
                    label = _text((f["priorities"] or {}).get(p), "Priority name", 20)
                    if label:
                        d["priorities"][p] = label
            self._save_tasks(d)
            return {"ok": True, "types": d["types"], "priorities": d["priorities"]}

    def save_statuses(self, f):
        """Built-in statuses: label and colour. Custom ones: everything, plus add / delete."""
        with self.lock:
            d = self._load_tasks()
            for k, v in (f.get("builtin") or {}).items():
                if k not in BUILTIN_STATUSES:
                    continue
                label = _text(v.get("label"), "Status name", 30) or BUILTIN_STATUSES[k]["label"]
                d["statuses"]["builtin"][k] = {"label": label, "color": v.get("color") if v.get("color") in COLORS else BUILTIN_STATUSES[k]["color"]}
            if "custom" in f:
                out, seen = [], set()
                labels = {v["label"].lower() for v in d["statuses"]["builtin"].values()}
                for raw in f["custom"] or []:
                    label = _text(raw.get("label"), "Status name", 40)
                    if not label:
                        raise Fail("Every status code needs a name")
                    if label.lower() in labels or label.lower() in {x["label"].lower() for x in out}:
                        raise Fail(f"There is already a status called {label}")
                    sid = raw.get("id") if re.match(r"^s_[a-z0-9_]{1,30}$", str(raw.get("id") or "")) else _new_id("s_", seen)
                    if sid in seen:
                        sid = _new_id("s_", seen)
                    seen.add(sid)
                    exp = raw.get("expiry") if raw.get("expiry") in STATUS_EXPIRY else "never"
                    s = {"id": sid, "label": label, "color": raw.get("color") if raw.get("color") in COLORS else "purple",
                         "help": _text(raw.get("help"), f"{label} description", 200, safe=False),
                         "list": raw.get("list") if raw.get("list") in STATUS_LISTS else "own",
                         "boot_prompt": _flag(raw.get("boot_prompt")), "note_required": _flag(raw.get("note_required")),
                         "clock": raw.get("clock") if raw.get("clock") in STATUS_CLOCK else "none",
                         "expiry": exp, "expiry_days": _num(raw.get("expiry_days") or 0, f"{label} days", 0, 365, integer=True) if exp == "days" else 0,
                         "log_option": _flag(raw.get("log_option"))}
                    if exp == "days" and s["expiry_days"] < 1:
                        raise Fail(f"{label}: give the number of days before it ends by itself")
                    out.append(s)
                if len(out) > MAX_STATUSES:
                    raise Fail(f"At most {MAX_STATUSES} status codes")
                in_use = {t["hold"]["status"] for t in d["tasks"].values() if t.get("hold")}
                gone = [c["label"] for c in d["statuses"]["custom"] if c["id"] not in seen and c["id"] in in_use]
                if gone:
                    raise Fail(f"Tasks are set to {', '.join(gone)} - clear them first")
                d["statuses"]["custom"] = out
            self._save_tasks(d)
            return {"ok": True, "statuses": list(self.status_defs(d).values())}

