"""Values the Rhino's tuning wizards found, kept where Klipper can read them without SAVE_CONFIG (1.9.48, docs/proposal-tuning-wizards-2.md).

    myrhino/tuned.json   {"schema": 1, "rev": n, "updated": t, "pid": {"extruder": {"kp", "ki", "kd", "at", "previous"}, ...}}
    myrhino/tuned.cfg    GENERATED from it, never edited by hand; printer.cfg includes it AFTER tools/3dp.cfg

Why not SAVE_CONFIG: PID_CALIBRATE ends by asking for it, but Klipper refuses to start when a saved value conflicts with one in an
included file (configfile.py `_disallow_include_conflicts`), and the hotend's and bed's PID values are in tools/3dp.cfg. A later
included file simply overrides an earlier one ("overrides in includes apply linearly"), so tuned.cfg can carry the new numbers and the
original file stays as it was. Klipper cannot change PID while running, so a restart applies a change (the Portal marks it pending;
it never restarts Klipper itself).

A heater section is only written while the heater exists in the config: a `[heater_generic X]` with only PID options would be an
incomplete heater and Klipper would not start. The file is parsed back the way Klipper reads it before it is kept, and written atomically.
"""
import os
import re
import time

from . import atomic, pending, sections
from .errors import Fail
from .versioned_store import SCHEMA, _LOCK, _read, _write

HEADER = """# GENERATED by the rhino package (Rhino Studio, Wizards) - do not edit by hand.
# Values the tuning wizards found (PID for heaters). Rewritten on every save. printer.cfg includes this file after tools/3dp.cfg,
# so a value here overrides the same value there. Klipper reads it at the next restart. Delete a heater's block in Studio
# (Wizards > Tune a heater > Put back what it had), not here.
"""
EMPTY = {"schema": SCHEMA, "rev": 0, "updated": 0, "pid": {}, "accelerometer": None, "shaper": {}, "shaper_active": None}
SHAPERS = ("zv", "mzv", "zvd", "ei", "2hump_ei", "3hump_ei")
_HEAD = re.compile(r"^[A-Za-z0-9_.-]{1,40}$")
_SERIAL = re.compile(r"^/dev/serial/by-id/[\w.:+-]{1,120}$")
_NAME = re.compile(r"^[A-Za-z0-9_-]{1,40}$")
GAIN_MAX = 10000.0


def heater_key(obj):
    """'extruder' -> 'extruder', 'heater_bed' -> 'heater_bed', 'heater_generic chamber' -> 'chamber'. Anything else -> Fail."""
    if obj in ("extruder", "heater_bed"):
        return obj
    kind, _, rest = (obj or "").partition(" ")
    if kind == "heater_generic" and _NAME.match(rest or ""):
        return rest
    raise Fail("Pick a heater: the hotend (extruder), the bed (heater_bed) or a heater_generic one.")


def _gain(v, name):
    if isinstance(v, bool) or not isinstance(v, (int, float)) or v != v or not 0 < v < GAIN_MAX:
        raise Fail(f"{name} must be a number above 0 and below {GAIN_MAX:g}")
    return round(float(v), 4)


def _num(v, name, lo, hi):
    if isinstance(v, bool) or not isinstance(v, (int, float)) or v != v or not lo <= v <= hi:
        raise Fail(f"{name} must be a number from {lo:g} to {hi:g}")
    return round(float(v), 3)


def clean_accelerometer(raw):
    """{"serial", "cs_pin", "spi_bus", "axes_map", "probe": {x, y, z}} -> the same, checked."""
    if not isinstance(raw, dict):
        raise Fail("Expected the accelerometer's settings")
    serial, cs, bus, axes = raw.get("serial"), raw.get("cs_pin"), raw.get("spi_bus"), raw.get("axes_map")
    if not isinstance(serial, str) or not _SERIAL.match(serial):
        raise Fail("The serial name must look like /dev/serial/by-id/usb-Klipper_rp2040_... (see ls /dev/serial/by-id/)")
    if not isinstance(cs, str) or not re.match(r"^adxl:gpio\d{1,2}$", cs):
        raise Fail("The chip-select pin must look like adxl:gpio1")
    if not isinstance(bus, str) or not re.match(r"^spi\d[a-z]?$", bus):
        raise Fail("The SPI bus must look like spi0a")
    if not isinstance(axes, str) or not re.match(r"^-?[xyz],-?[xyz],-?[xyz]$", axes):
        raise Fail("The axes map must look like x,y,z")
    pr = raw.get("probe")
    if not isinstance(pr, dict):
        raise Fail("Where to measure (probe_points) is missing")
    return {"serial": serial, "cs_pin": cs, "spi_bus": bus, "axes_map": axes,
            "probe": {"x": _num(pr.get("x"), "X", 0, 2000), "y": _num(pr.get("y"), "Y", 0, 2000), "z": _num(pr.get("z"), "Z", 0, 2000)}}


def clean_pick(raw, axis):
    if not isinstance(raw, dict) or raw.get("type") not in SHAPERS:
        raise Fail(f"The {axis} shaper must be one of {', '.join(SHAPERS)}")
    return {"type": raw["type"], "freq": _num(raw.get("freq"), f"The {axis} frequency", 10, 200)}


def render(pid, existing, accel=None, shaper=None):
    """The whole tuned.cfg. `existing`: heater keys Klipper has (a kept value for a heater that is gone is left out, with a note).
    `accel`: the accelerometer board; `shaper`: the print head's pick whose [input_shaper] Klipper loads at start."""
    out = [HEADER]
    if accel:
        p = accel["probe"]
        out.append(f"[mcu adxl]\nserial: {accel['serial']}\n\n[adxl345]\ncs_pin: {accel['cs_pin']}\nspi_bus: {accel['spi_bus']}\naxes_map: {accel['axes_map']}\n\n"
                   f"[resonance_tester]\naccel_chip: adxl345\nprobe_points: {p['x']:g},{p['y']:g},{p['z']:g}\n")
    if shaper:
        out.append(f"[input_shaper]\nshaper_type_x: {shaper['x']['type']}\nshaper_freq_x: {shaper['x']['freq']:g}\n"
                   f"shaper_type_y: {shaper['y']['type']}\nshaper_freq_y: {shaper['y']['freq']:g}\n")
    for obj in sorted(pid):
        v = pid[obj]
        if heater_key(obj) not in existing:
            out.append(f"# {obj}: kept values not written, Klipper has no such heater now\n")
            continue
        out.append(f"[{obj}]\ncontrol: pid\npid_Kp: {v['kp']:g}\npid_Ki: {v['ki']:g}\npid_Kd: {v['kd']:g}\n")
    return "\n".join(out)


class Tuned:
    def __init__(self, paths, now=time.time):
        self.paths, self.now = paths, now
        my = os.path.join(paths.cfg, "myrhino")
        self.file = os.path.join(my, "tuned.json")
        self.cfg = os.path.join(my, "tuned.cfg")

    def _load(self):
        d, ok = _read(self.file, EMPTY)
        if not ok:
            raise Fail("myrhino/tuned.json can't be read, so it's kept as it is. Fix or remove it by hand.")
        return d

    def state(self, restart_needed=None):
        d = self._load()
        out = {"ok": True, "rev": d["rev"], "updated": d["updated"], "pid": d["pid"], "accelerometer": d.get("accelerometer"),
               "shaper": d.get("shaper", {}), "shaper_active": d.get("shaper_active")}
        out["restart_needed"] = bool(pending.get(self.paths)) if restart_needed is None else restart_needed
        return out

    def _write(self, d, existing):
        active = d.get("shaper_active")
        text = render(d["pid"], existing, d.get("accelerometer"), d.get("shaper", {}).get(active) if active else None)
        sections.parse_like_klipper(text)                 # never write a file Klipper can't read
        _write(self.file, d)
        atomic.write_text(self.cfg, text)

    def set_pid(self, raw, existing):
        """{"rev", "heater": "extruder", "kp", "ki", "kd"}: keep a heater's PID values."""
        if not isinstance(raw, dict):
            raise Fail("Expected the PID values")
        with _LOCK:
            d = self._load()
            if raw.get("rev") != d["rev"]:
                raise Fail(f"Tuned values were changed on another screen (now revision {d['rev']}). Reload, then save again.")
            obj = raw.get("heater")
            if heater_key(obj) not in existing:
                raise Fail(f"Klipper has no heater called {heater_key(obj)}.")
            new = {"kp": _gain(raw.get("kp"), "Kp"), "ki": _gain(raw.get("ki"), "Ki"), "kd": _gain(raw.get("kd"), "Kd"), "at": int(self.now())}
            old = d["pid"].get(obj)
            new["previous"] = {k: old[k] for k in ("kp", "ki", "kd")} if old else None
            d = {**d, "rev": d["rev"] + 1, "updated": int(self.now()), "pid": {**d["pid"], obj: new}}
            self._write(d, existing)
        pending.mark(self.paths, f"tuned PID for {obj} (tuned.cfg)")
        return self.state(True)

    def clear(self, raw, existing):
        """{"rev", "heater"}: forget a heater's kept values, so it goes back to what its own config says."""
        if not isinstance(raw, dict):
            raise Fail("Expected a heater")
        with _LOCK:
            d = self._load()
            if raw.get("rev") != d["rev"]:
                raise Fail(f"Tuned values were changed on another screen (now revision {d['rev']}). Reload, then save again.")
            obj = raw.get("heater")
            heater_key(obj)
            if obj not in d["pid"]:
                raise Fail("Nothing is kept for that heater.")
            pid = {k: v for k, v in d["pid"].items() if k != obj}
            d = {**d, "rev": d["rev"] + 1, "updated": int(self.now()), "pid": pid}
            self._write(d, existing)
        pending.mark(self.paths, f"removed tuned PID for {obj} (tuned.cfg)")
        return self.state(True)

    def set_accelerometer(self, raw, existing):
        """{"rev", "serial", "cs_pin", "spi_bus", "axes_map", "probe"}: keep the accelerometer board (tuned.cfg gets [mcu adxl], [adxl345], [resonance_tester])."""
        with _LOCK:
            d = self._load()
            self._rev(raw, d)
            d = {**d, "rev": d["rev"] + 1, "updated": int(self.now()), "accelerometer": clean_accelerometer(raw)}
            self._write(d, existing)
        pending.mark(self.paths, "accelerometer settings (tuned.cfg)")
        return self.state(True)

    def set_shaper(self, raw, existing):
        """{"rev", "head", "x": {type, freq}, "y": {...}, "max_accel"}: keep the input shaper picked for a print head. The last one kept is what
        Klipper loads at start (per-head switching at a job start is a macro change, docs/proposal-per-head-shaping.md)."""
        with _LOCK:
            d = self._load()
            self._rev(raw, d)
            head = raw.get("head")
            if not isinstance(head, str) or not _HEAD.match(head):
                raise Fail("Which print head?")
            ma = raw.get("max_accel")
            ma = None if ma is None else int(_num(ma, "The maximum acceleration", 100, 100000))
            pick = {"x": clean_pick(raw.get("x"), "X"), "y": clean_pick(raw.get("y"), "Y"), "max_accel": ma, "at": int(self.now())}
            d = {**d, "rev": d["rev"] + 1, "updated": int(self.now()), "shaper": {**d.get("shaper", {}), head: pick}, "shaper_active": head}
            self._write(d, existing)
        pending.mark(self.paths, f"input shaper for {head} (tuned.cfg)")
        return self.state(True)

    def clear_shaper(self, raw, existing):
        with _LOCK:
            d = self._load()
            self._rev(raw, d)
            head = raw.get("head")
            if head not in d.get("shaper", {}):
                raise Fail("Nothing is kept for that print head.")
            rest = {k: v for k, v in d["shaper"].items() if k != head}
            active = d.get("shaper_active")
            if active == head:
                active = max(rest, key=lambda k: rest[k]["at"]) if rest else None
            d = {**d, "rev": d["rev"] + 1, "updated": int(self.now()), "shaper": rest, "shaper_active": active}
            self._write(d, existing)
        pending.mark(self.paths, f"removed the input shaper for {head} (tuned.cfg)")
        return self.state(True)

    @staticmethod
    def _rev(raw, d):
        if not isinstance(raw, dict):
            raise Fail("Expected a request")
        if raw.get("rev") != d["rev"]:
            raise Fail(f"Tuned values were changed on another screen (now revision {d['rev']}). Reload, then save again.")
