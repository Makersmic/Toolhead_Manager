#!/usr/bin/env python3
"""The config change for tuned heater values (docs/proposal-tuning-wizards-2.md; Mike approved Nov 23).

    python3 dev/proposal_tuned_cfg.py            print the diff (changes nothing)
    python3 dev/proposal_tuned_cfg.py --apply    add `[include myrhino/tuned.cfg]` to printer.cfg (a second run is refused)

The include goes AFTER tools/3dp.cfg, because a later included file overrides an earlier one (Klipper's configfile.py applies
overrides in includes linearly), and the hotend's and bed's PID values live in tools/3dp.cfg. Adds one line; nothing else changes."""
import difflib
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
FILE = "printer.cfg"
ANCHOR = "[include tools/3dp.cfg]"
LINE = "[include myrhino/tuned.cfg]"


def main(apply=False):
    path = os.path.join(ROOT, FILE)
    old = open(path, encoding="utf-8").read()
    if LINE in old:
        raise SystemExit("Already applied: printer.cfg includes myrhino/tuned.cfg.")
    lines = old.split("\n")
    hits = [i for i, l in enumerate(lines) if l.strip() == ANCHOR]
    if len(hits) != 1:
        raise SystemExit(f"Anchor {ANCHOR!r} found {len(hits)} times: nothing changed.")
    lines[hits[0] + 1:hits[0] + 1] = ["# Values the tuning wizards found (PID); overrides tools/3dp.cfg, so it must stay after it. Generated by the Portal.", LINE]
    new = "\n".join(lines)
    sys.stdout.writelines(difflib.unified_diff(old.splitlines(True), new.splitlines(True), f"a/{FILE}", f"b/{FILE}", n=1))
    if apply:
        open(path, "w", encoding="utf-8").write(new)


if __name__ == "__main__":
    main("--apply" in sys.argv)
