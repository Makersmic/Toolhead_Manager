#!/usr/bin/env python3
"""Generate rhino/hw_boards_data.py from a Klipper checkout (Add hardware wizard, step 2).

    python3 scripts/board_pins_from_klipper.py <klipper checkout> rhino/hw_boards_data.py

Reads the board reference configs Klipper ships (config/generic-*.cfg, sample-*.cfg), including their
commented-out blocks, which name the spare headers (HE1, T2, the extra endstops...). For each pin it
records what the board wires it to (heater / fan MOSFET, thermistor header, endstop header, driver...)
and the silk label from a trailing "# HE0"-style comment when there is one.

Only facts (pin numbers and header names) are taken, not Klipper code. Change boards here, then re-run;
never hand-edit the generated file.
"""
import os
import re
import sys

# preset id -> (Klipper config file, label, MCU family key in rhino/hw_boards.py)
BOARDS = {
    "octopus_v1_1":    ("generic-bigtreetech-octopus-v1.1.cfg", "BTT Octopus v1.1 (STM32F446)", "stm32f446"),
    "skr_mini_e3_v3":  ("generic-bigtreetech-skr-mini-e3-v3.0.cfg", "BTT SKR Mini E3 v3.0", "stm32g0b1"),
    "ebb_v1_2":        ("sample-bigtreetech-ebb-canbus-v1.2.cfg", "BTT EBB36 / EBB42 v1.2", "stm32g0b1"),
    "ebb_sb_v1_0":     ("sample-bigtreetech-ebb-sb-canbus-v1.0.cfg", "BTT EBB SB2209 / SB2240 v1.0", "stm32g0b1"),
    "skr_pico_v1_0":   ("generic-bigtreetech-skr-pico-v1.0.cfg", "BTT SKR Pico v1.0", "rp2040"),
}

_SECTION = re.compile(r"^\s*#*\s*\[([^\]]+)\]")
_KEY = re.compile(r"^\s*#*\s*([a-z_0-9]+)\s*[:=]\s*(.+)$")
_PIN = re.compile(r"^[!^~]*(?:[A-Za-z0-9_]+:)?[!^~]*(P[A-K][0-9]{1,2}|gpio[0-9]{1,2})$", re.I)
_HEATERS = ("extruder", "heater_bed", "heater_generic")
_FANS = ("fan", "heater_fan", "controller_fan", "fan_generic", "temperature_fan")
_DRIVER_KEYS = ("step_pin", "dir_pin", "enable_pin", "uart_pin", "tx_pin", "diag_pin")
_SPI_KEYS = ("cs_pin", "spi_software_sclk_pin", "spi_software_mosi_pin", "spi_software_miso_pin")


def use_of(section, key):
    kind = section.split()[0].lower()
    base = re.sub(r"\d+$", "", kind)
    if key == "heater_pin" and base in _HEATERS:
        return "heater"
    if key == "pin" and base in _FANS:
        return "fan"
    if key == "sensor_pin" and base in _HEATERS + ("temperature_sensor",):
        return "thermistor"
    if key in ("endstop_pin", "switch_pin"):
        return "endstop"
    if key in ("sensor_pin",) and base in ("probe", "bltouch"):
        return "probe"
    if key == "control_pin":
        return "servo"
    if key == "pin" and base in ("neopixel", "dotstar"):
        return "rgb"
    if key in _DRIVER_KEYS:
        return "driver"
    if key in _SPI_KEYS:
        return "spi"
    return "gpio"


def canon(pin):
    pin = pin.strip()
    return pin.lower() if pin.lower().startswith("gpio") else pin.upper()


def parse(path):
    """-> {pin: {"use", "header", "where"}} for every pin the file names, live or commented out."""
    out, section = {}, ""
    with open(path, encoding="utf-8") as f:
        for line in f:
            m = _SECTION.match(line)
            if m:
                section = m.group(1).strip()
                continue
            m = _KEY.match(line)
            if not m or not section:
                continue
            key, rest = m.group(1).lower(), m.group(2)
            value, _, comment = rest.partition("#")
            tok = value.strip().split()[0] if value.strip() else ""
            pm = _PIN.match(tok)
            if not pm:
                continue
            pin = canon(pm.group(1))
            use = use_of(section, key)
            header = comment.strip() if re.match(r"^[A-Z][A-Z0-9_-]{0,7}$", comment.strip()) else ""
            prev = out.get(pin)
            # first live mention wins; a later "driver" never hides a header use found earlier
            if prev and (prev["use"] != "gpio" or use == "gpio"):
                if header and not prev["header"]:
                    prev["header"] = header
                continue
            out[pin] = {"use": use, "header": header or (prev or {}).get("header", ""), "where": f"{section} {key}"}
    return out


def main(klipper, dest):
    rev = ""
    head = os.path.join(klipper, ".git", "HEAD")
    if os.path.exists(head):
        rev = os.popen(f"git -C {klipper!r} rev-parse --short HEAD").read().strip()
    lines = ['"""GENERATED by scripts/board_pins_from_klipper.py from Klipper\'s board configs'
             f'{" at " + rev if rev else ""} - do not edit by hand.',
             "", "Pin -> what the board wires it to (use), the silk label when Klipper's config names it (header),",
             'and where in the reference config it came from (where)."""', "", "BOARDS = {"]
    for bid, (fname, label, mcu) in BOARDS.items():
        pins = parse(os.path.join(klipper, "config", fname))
        lines.append(f"    {bid!r}: {{")
        lines.append(f"        'label': {label!r}, 'mcu': {mcu!r}, 'source': {('config/' + fname)!r},")
        lines.append("        'pins': {")
        for p in sorted(pins, key=lambda s: (re.sub(r"\d+$", "", s), int(re.search(r"\d+$", s).group(0)))):
            d = pins[p]
            lines.append(f"            {p!r}: {{'use': {d['use']!r}, 'header': {d['header']!r}, 'where': {d['where']!r}}},")
        lines.append("        },")
        lines.append("    },")
    lines.append("}")
    with open(dest, "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")
    print(f"wrote {dest}: {len(BOARDS)} boards")


if __name__ == "__main__":
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    main(sys.argv[1], sys.argv[2])
